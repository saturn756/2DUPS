#!/usr/bin/env python3
"""生成 KITTI Road 的 I1 清单（一张训练图一个样本，`annotation_ref` 指向其 GT 掩码）。

为什么生成而不是提交：289 条样本会让 `configs/` 多出上千行，而 KITTI 数据本身就在
git 忽略的 `data/raw/` 下。清单写到数据目录内，由本脚本确定性重建；
重建命令与结果哈希记在 docs 与 changelog 里。

用法：
    python scripts/make_kitti_road_manifest.py
    python scripts/make_kitti_road_manifest.py --data data/raw/kitti_road --split eval
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
import struct

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from twodups.contracts.base import Ref  # noqa: E402
from twodups.contracts.i1_dataset_manifest import DatasetManifest, Sample  # noqa: E402
from twodups.contracts.i2_calibrated_frame import ImageSize  # noqa: E402
from twodups.data.calibration import kitti_camera_payload  # noqa: E402
from twodups.data.manifest import dump  # noqa: E402
from twodups.utils.config import REPO_ROOT  # noqa: E402

GT_KIND = "segmentation_mask"
IMAGE_KIND = "image_file"


def _gt_stem(image_stem: str) -> str:
    """`um_000000` → `um_road_000000` 的基名（road 标签）。"""
    prefix, number = image_stem.split("_", 1)
    return f"{prefix}_road_{number}"


def main() -> int:
    parser = argparse.ArgumentParser(description="生成 KITTI Road 的 I1 清单")
    parser.add_argument("--data", type=Path, default=Path("data/raw/kitti_road"))
    parser.add_argument("--split", default="eval")
    parser.add_argument("--manifest", type=Path, help="默认 <data>/manifest.yaml")
    args = parser.parse_args()

    data_dir = args.data if args.data.is_absolute() else REPO_ROOT / args.data
    image_dir = data_dir / "training" / "image_2"
    gt_dir = data_dir / "training" / "gt_image_2"
    calib_dir = data_dir / "training" / "calib"
    if not image_dir.is_dir() or not gt_dir.is_dir() or not calib_dir.is_dir():
        raise SystemExit(f"missing training/image_2, gt_image_2 or calib under {data_dir}")
    normalized_calib_dir = data_dir / "calibration"
    normalized_calib_dir.mkdir(parents=True, exist_ok=True)

    samples: list[Sample] = []
    missing_gt: list[str] = []
    categories: dict[str, int] = {}
    for image in sorted(image_dir.glob("*.png")):
        stem = image.stem
        gt = gt_dir / f"{_gt_stem(stem)}.png"
        native_calib = calib_dir / f"{stem}.txt"
        if not gt.is_file():
            missing_gt.append(stem)
            continue
        if not native_calib.is_file():
            raise SystemExit(f"missing calibration for {stem}: {native_calib}")
        category = stem.split("_", 1)[0]
        categories[category] = categories.get(category, 0) + 1
        uri = image.relative_to(REPO_ROOT).as_posix()
        gt_uri = gt.relative_to(REPO_ROOT).as_posix()
        image_bytes = image.read_bytes()
        if image_bytes[:8] != b"\x89PNG\r\n\x1a\n":
            raise SystemExit(f"expected PNG image: {image}")
        width, height = struct.unpack(">II", image_bytes[16:24])
        native_bytes = native_calib.read_bytes()
        native_uri = native_calib.relative_to(REPO_ROOT).as_posix()
        native_checksum = "sha256:" + hashlib.sha256(native_bytes).hexdigest()
        payload = kitti_camera_payload(
            native_bytes.decode("utf-8"),
            image_size=ImageSize(width=width, height=height),
            source_uri=native_uri,
            source_checksum=native_checksum,
        )
        normalized_path = normalized_calib_dir / f"{stem}.json"
        normalized_bytes = (json.dumps(payload, ensure_ascii=False, sort_keys=True,
                                       indent=2) + "\n").encode("utf-8")
        normalized_path.write_bytes(normalized_bytes)
        normalized_uri = normalized_path.relative_to(REPO_ROOT).as_posix()
        normalized_checksum = "sha256:" + hashlib.sha256(normalized_bytes).hexdigest()
        samples.append(Sample(
            sample_id=stem, sequence_id=stem,
            media_ref=Ref(uri=uri, kind=IMAGE_KIND),
            annotation_ref=Ref(uri=gt_uri, kind=GT_KIND),
            slice_tags=[category, "daytime"],
            fps=None,          # 单帧，没有序列也没有 PTS
            calibration_ref=Ref(uri=normalized_uri, kind="camera_params",
                                checksum=normalized_checksum),
        ))
    if missing_gt:
        raise SystemExit(f"{len(missing_gt)} images have no road mask, e.g. {missing_gt[:3]}")
    if not samples:
        raise SystemExit("no samples found")

    manifest = DatasetManifest(
        manifest_id="kitti-road-training",
        version="1",
        source="KITTI_ROAD",
        license="KITTI Road benchmark, academic non-commercial use, no redistribution",
        samples=samples,
        splits={args.split: [sample.sample_id for sample in samples]},
        config_ref="<generated by scripts/make_kitti_road_manifest.py>",
    )
    manifest_path = args.manifest or (data_dir / "manifest.yaml")
    checksum = dump(manifest, manifest_path, header=[
        "# 由 scripts/make_kitti_road_manifest.py 从 data/raw/kitti_road/training 生成",
        "# 一张训练图一个样本；GT 掩码（road）作为 annotation_ref；不提交到 Git。",
    ])
    print(json.dumps({
        "samples": len(samples),
        "categories": categories,
        "split": args.split,
        "manifest": str(manifest_path),
        "checksum": checksum,
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
